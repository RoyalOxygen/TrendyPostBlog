<?php
if (!defined('TRENDYPOST')) {
    define('TRENDYPOST', true);
    require_once __DIR__ . '/../config/config.php';
    require_once INCLUDES_PATH . 'Database.php';
    require_once INCLUDES_PATH . 'Helpers.php';
    require_once INCLUDES_PATH . 'Models.php';
}
header('Content-Type: text/plain; charset=UTF-8');

$sitemapUrl = url('sitemap.xml');

// Private areas and duplicate URLs never belong in the index. Public content
// (posts, pages, categories, tags, authors, sitemaps) is always crawlable.
$disallow = [
    '/admin/',
    '/api/',
    '/login',
    '/register',
    '/logout',
    '/forgot-password',
    '/reset-password',
    '/preview/',
    '/newsletter/',
    '/install/',
];

$lines = ['User-agent: *'];
foreach ($disallow as $path) {
    $lines[] = 'Disallow: ' . $path;
}
$lines[] = 'Allow: /';
$lines[] = '';
// Let image crawlers index the article images.
$lines[] = 'User-agent: Googlebot-Image';
$lines[] = 'Allow: /';
$lines[] = '';
$lines[] = 'Sitemap: ' . $sitemapUrl;

echo implode("\n", $lines) . "\n";
echo "\n# Auto-generated by TrendyPost\n# Last updated: " . date('c') . "\n";
